export function buildPrompt({ from = '', to = '', mode = '', when = '', context = [], question = '' } = {}) {
  const lines = [
    '나는 중국 여행이 처음인 한국인이고 중국어를 거의 못 해. 상하이 여행 중이야.',
  ];
  const route = [from && `출발: ${from}`, to && `도착: ${to}`, mode && `이동 수단: ${mode}`, when && `언제: ${when}`].filter(Boolean);
  if (route.length) lines.push('', ...route);
  const ctx = context.filter(Boolean);
  if (ctx.length) lines.push('', '참고 정보:', ...ctx.map(c => `- ${c}`));
  lines.push('', question || '출발지에서 목적지까지 가는 방법을 알려줘.');
  lines.push('',
    '이렇게 답해 줘:',
    '1. 번호 매긴 단계별 안내 — 어느 출구로 나가서, 몇 층으로, 어느 쪽 에스컬레이터를 타는지, 여권 확인·짐검사 지점, 개찰구·검표구 찾는 법, 플랫폼에서 서는 위치까지',
    '2. 따라가야 할 표지판 중국어는 한자 + 한국어 뜻으로',
    '3. 외국인(여권)이라 막히기 쉬운 지점과 대처법, 걸리는 시간',
    '4. 출구 번호·층수처럼 확실하지 않은 건 추측하지 말고 "현장 확인 필요"라고 표시. 가능하면 최신 정보를 검색하고 출처를 알려줘.');
  return lines.join('\n');
}
