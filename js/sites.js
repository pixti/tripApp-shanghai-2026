export function findSite(stop) {
  if (!stop) return null;
  const text = `${stop.zh || ''} ${stop.name || ''}`;
  return SITES.find(s => s.match.test(text)) || null;
}

// ── 개략도 그리기 ─────────────────────────────────────────
function el(tag, attrs = {}, ...kids) {
  const e = document.createElementNS(SVG, tag);
  for (const [k, v] of Object.entries(attrs)) if (v != null && v !== false) e.setAttribute(k, v);
  for (const k of kids.flat()) if (k != null) e.append(k instanceof Node ? k : document.createTextNode(String(k)));
  return e;
}

const pts = arr => arr.map(p => p.join(',')).join(' ');

// 경유점을 부드러운 곡선으로 (Catmull-Rom → 베지어)
function smooth(p) {
  if (p.length < 3) return `M${pts(p)}`;
  let d = `M${p[0][0]},${p[0][1]}`;
  for (let i = 0; i < p.length - 1; i++) {
    const p0 = p[i - 1] || p[i];
    const p1 = p[i];
    const p2 = p[i + 1];
    const p3 = p[i + 2] || p2;
    const t = 0.18;
    const c1 = [p1[0] + (p2[0] - p0[0]) * t, p1[1] + (p2[1] - p0[1]) * t];
    const c2 = [p2[0] - (p3[0] - p1[0]) * t, p2[1] - (p3[1] - p1[1]) * t];
    d += ` C${c1[0].toFixed(1)},${c1[1].toFixed(1)} ${c2[0].toFixed(1)},${c2[1].toFixed(1)} ${p2[0]},${p2[1]}`;
  }
  return d;
}

const LABEL_POS = {
  r: (x, y) => ({ x: x + 8, y: y + 3, anchor: 'start' }),
  l: (x, y) => ({ x: x - 8, y: y + 3, anchor: 'end' }),
  t: (x, y) => ({ x, y: y - 8, anchor: 'middle' }),
  b: (x, y) => ({ x, y: y + 13, anchor: 'middle' }),
};

export function siteMapSvg(site, { onSpot } = {}) {
  const H = site.h || 260;
  const svg = el('svg', { viewBox: `0 0 400 ${H}`, class: 'site-svg', role: 'img', 'aria-label': `${site.name} 동선 개략도` });
  svg.append(el('rect', { x: 0, y: 0, width: 400, height: H, class: 'sm-bg' }));
  svg.append(el('polygon', { points: pts(site.land), class: 'sm-land' }));
  for (const w of site.walls || []) svg.append(el('polyline', { points: pts(w), class: 'sm-wall' }));
  for (const [cx, cy, rx, ry] of site.hills || []) svg.append(el('ellipse', { cx, cy, rx, ry, class: 'sm-hill' }));
  for (const w of site.water || []) svg.append(el('polygon', { points: pts(w), class: 'sm-water' }));
  for (const [cx, cy, rx, ry] of site.islands || []) svg.append(el('ellipse', { cx, cy, rx, ry, class: 'sm-island' }));
  if (site.zigzag) svg.append(el('polyline', { points: pts(site.zigzag), class: 'sm-bridge' }));
  for (const z of site.zones || []) svg.append(el('text', { x: z.x, y: z.y, class: 'sm-zone', 'text-anchor': 'middle' }, z.t));

  // 동선
  svg.append(el('path', { d: smooth(site.route), class: 'sm-route-casing' }));
  svg.append(el('path', { d: smooth(site.route), class: 'sm-route' }));
  // 방향 화살표 (긴 구간 가운데)
  const r = site.route;
  for (let i = 0; i < r.length - 1; i++) {
    const [x1, y1] = r[i];
    const [x2, y2] = r[i + 1];
    const len = Math.hypot(x2 - x1, y2 - y1);
    if (len < 26) continue;
    const ang = Math.atan2(y2 - y1, x2 - x1) * 180 / Math.PI;
    svg.append(el('path', { d: 'M-3.5,-3 L3.5,0 L-3.5,3 Z', class: 'sm-arrow', transform: `translate(${(x1 + x2) / 2},${(y1 + y2) / 2}) rotate(${ang.toFixed(0)})` }));
  }

  // 이름만 있는 곳
  for (const s of site.side || []) {
    const g = el('g', { class: 'sm-side' });
    g.append(el('circle', { cx: s.x, cy: s.y, r: 1.8 }));
    if (s.vertical) g.append(el('text', { x: s.x + 3, y: s.y - 14, class: 'sm-side-t', 'writing-mode': 'tb' }, s.zh));
    else g.append(el('text', { x: s.x, y: s.y - 4, class: 'sm-side-t', 'text-anchor': 'middle' }, s.zh));
    svg.append(g);
  }

  // 화장실
  for (const [x, y] of site.wc || []) {
    svg.append(el('g', { class: 'sm-wc', transform: `translate(${x},${y})` }, el('rect', { x: -6, y: -4.5, width: 12, height: 9, rx: 2 }), el('text', { x: 0, y: 2.6, 'text-anchor': 'middle' }, 'WC')));
  }

  // 출입구
  for (const g of site.gates || []) {
    const w = g.t.length * (g.small ? 6.5 : 8) + 8;
    svg.append(el('g', { class: `sm-gate ${g.exit ? 'exit' : ''} ${g.small ? 'small' : ''}`, transform: `translate(${Math.min(Math.max(g.x, w / 2 + 2), 398 - w / 2)},${Math.min(g.y, H - 7)})` },
      el('rect', { x: -w / 2, y: -6.5, width: w, height: 13, rx: 3 }),
      el('text', { x: 0, y: 3.2, 'text-anchor': 'middle' }, g.t)));
  }

  // 번호 지점 (입구는 번호 대신 문 표시가 있어 건너뜀)
  site.spots.forEach((s, i) => {
    if (i === 0) return;
    const lp = LABEL_POS[s.lp || 'r'](s.x, s.y);
    const g = el('g', { class: `sm-spot ${s.must ? 'must' : ''}`, 'data-i': i, tabindex: 0 });
    g.append(el('text', { x: lp.x, y: lp.y, 'text-anchor': lp.anchor, class: 'sm-label' }, s.zh));
    g.append(el('circle', { cx: s.x, cy: s.y, r: 6.2, class: 'sm-dot' }));
    g.append(el('text', { x: s.x, y: s.y + 2.6, 'text-anchor': 'middle', class: 'sm-num' }, String(i)));
    if (onSpot) g.addEventListener('click', () => onSpot(i));
    svg.append(g);
  });

  // 북쪽 표시
  const [nx, ny] = site.north || [390, H - 24];
  svg.append(el('g', { class: 'sm-north', transform: `translate(${nx},${ny})` },
    el('path', { d: 'M0,-9 L4,3 L0,0 L-4,3 Z' }), el('text', { x: 0, y: 13, 'text-anchor': 'middle' }, 'N')));
  return svg;
}
